from __future__ import annotations

from PySide6.QtWidgets import (QCheckBox, QComboBox, QDialog, QDialogButtonBox, QFormLayout, QGroupBox, QLabel,
                               QLineEdit, QSpinBox, QVBoxLayout)

from ..model import Settings


class SettingsDialog(QDialog):
    def __init__(self, settings: Settings, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Deckoy settings")
        self.setMinimumWidth(460)
        f = QFormLayout()
        self.host = QLineEdit(settings.dock_host)
        self.host.setPlaceholderText("blank = find automatically")
        self.port = QSpinBox()
        self.port.setRange(0, 65535)
        self.port.setSpecialValueText("auto")
        self.port.setValue(settings.dock_port)
        self.brightness = QSpinBox()
        self.brightness.setRange(0, 100)
        self.brightness.setSuffix(" %")
        self.brightness.setValue(settings.brightness)
        self.sleep = QSpinBox()
        self.sleep.setRange(0, 65535)
        self.sleep.setSuffix(" s")
        self.sleep.setValue(settings.sleep_seconds)
        self.startup = QCheckBox("Start with Windows")
        self.startup.setChecked(settings.start_with_windows)
        f.addRow("Dock IP", self.host)
        f.addRow("Dock port", self.port)
        f.addRow("Brightness", self.brightness)
        f.addRow("Sleep timeout", self.sleep)
        f.addRow("", self.startup)

        self.proxy_box = QGroupBox("Proxy options")
        pf = QFormLayout(self.proxy_box)
        self.bind = QLineEdit(settings.proxy_bind)
        self.bind.setPlaceholderText("blank = this PC's LAN address (recommended)")
        self.deck_port = QSpinBox()
        self.deck_port.setRange(1, 65535)
        self.deck_port.setValue(settings.proxy_deck_port)
        self.dock_port = QSpinBox()
        self.dock_port.setRange(1, 65535)
        self.dock_port.setValue(settings.proxy_dock_port)
        self.forward_unknown = QCheckBox("Forward commands Deckoy doesn't know (off = log and acknowledge only)")
        self.forward_unknown.setChecked(settings.proxy_forward_unknown)
        self.naming = QComboBox()
        self.naming.addItem("Distinct names (\"... (Deckoy)\") with the dock's TXT", "distinct")
        self.naming.addItem("Same names as the real dock", "same")
        self.naming.setCurrentIndex(0 if settings.proxy_naming == "distinct" else 1)
        self.listen_all = QCheckBox("Listen on all of this PC's addresses (only this PC can connect)")
        self.listen_all.setChecked(settings.proxy_listen_all)
        pf.addRow("Advertise address", self.bind)
        pf.addRow("", self.listen_all)
        pf.addRow("Deck service port", self.deck_port)
        pf.addRow("Dock service port", self.dock_port)
        pf.addRow("mDNS names", self.naming)
        self.reannounce = QComboBox()
        self.reannounce.addItem("Re-announce the deck service (recommended)", "deck")
        self.reannounce.addItem("Re-announce dock and deck", "both")
        self.reannounce.addItem("Off (only log the drop)", "off")
        self.reannounce.setCurrentIndex(max(0, [k for k in ("deck", "both", "off")].index(settings.proxy_reannounce)))
        self.new_port = QCheckBox("... on a new port each time")
        self.new_port.setChecked(settings.proxy_reannounce_new_port)
        self.reannounce_delay = QSpinBox()
        self.reannounce_delay.setRange(0, 30000)
        self.reannounce_delay.setSuffix(" ms")
        self.reannounce_delay.setValue(settings.proxy_reannounce_delay_ms)
        pf.addRow("When the Elgato app drops", self.reannounce)
        pf.addRow("", self.new_port)
        pf.addRow("Pause before re-announcing", self.reannounce_delay)
        pf.addRow("", self.forward_unknown)

        lay = QVBoxLayout(self)
        lay.addLayout(f)
        lay.addWidget(self.proxy_box)
        note = QLabel("Only one program can drive the dock: Deckoy is the only program that talks to it and the Elgato app "
                      "connects to Deckoy (see the README for the redirection steps). Changing these settings restarts "
                      "the dock connection.")
        note.setWordWrap(True)
        lay.addWidget(note)
        bb = QDialogButtonBox(QDialogButtonBox.Ok | QDialogButtonBox.Cancel)
        bb.accepted.connect(self.accept)
        bb.rejected.connect(self.reject)
        lay.addWidget(bb)

    def apply_to(self, s: Settings) -> None:
        s.dock_host = self.host.text().strip()
        s.dock_port = self.port.value()
        s.brightness = self.brightness.value()
        s.sleep_seconds = self.sleep.value()
        s.start_with_windows = self.startup.isChecked()
        s.proxy_bind = self.bind.text().strip()
        s.proxy_listen_all = self.listen_all.isChecked()
        s.proxy_deck_port = self.deck_port.value()
        s.proxy_dock_port = self.dock_port.value()
        s.proxy_forward_unknown = self.forward_unknown.isChecked()
        s.proxy_naming = self.naming.currentData()
        s.proxy_reannounce = self.reannounce.currentData()
        s.proxy_reannounce_new_port = self.new_port.isChecked()
        s.proxy_reannounce_delay_ms = self.reannounce_delay.value()
